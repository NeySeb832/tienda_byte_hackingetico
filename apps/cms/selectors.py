"""Read-side queries for the cms app.

The home slides are a curated static definition until the ``Banner`` model exists;
templates already consume the same shape a database query will return later.
Category tiles come from ``apps.catalog.selectors.home_categories``.

Product photos come from Wikimedia Commons with free licences; their metadata is
generated by ``scripts/product_images.py`` into ``data/imagenes.json``.
"""

import json
from dataclasses import dataclass
from decimal import Decimal
from functools import cache
from pathlib import Path
from typing import TYPE_CHECKING

from django.urls import reverse

if TYPE_CHECKING:
    from apps.cms.models import LegalDocument

DATA_DIR = Path(__file__).resolve().parent / "data"
FREE_LICENSES = frozenset(
    {
        "Public domain",
        "CC0",
        "CC BY 2.0",
        "CC BY 3.0",
        "CC BY 4.0",
        "CC BY-SA 2.0",
        "CC BY-SA 3.0",
        "CC BY-SA 4.0",
    }
)


@dataclass(frozen=True, slots=True)
class ImageCredit:
    slug: str
    file: str
    width: int
    height: int
    alt: str
    title: str
    author: str
    license: str
    license_url: str
    source: str


@dataclass(frozen=True, slots=True)
class Slide:
    eyebrow: str
    title: str
    text: str
    image: ImageCredit
    cta_label: str
    cta_href: str
    theme: str
    price_from: Decimal | None = None
    secondary_label: str = ""
    secondary_href: str = ""


def current_legal_document(kind: str) -> "LegalDocument | None":
    """Latest published version of a legal document."""
    from django.utils import timezone

    from apps.cms.models import LegalDocument

    return (
        LegalDocument.objects.filter(kind=kind, published_at__lte=timezone.now())
        .order_by("-published_at")
        .first()
    )


@cache
def _credits() -> dict[str, ImageCredit]:
    raw = json.loads((DATA_DIR / "imagenes.json").read_text(encoding="utf-8"))
    return {item["slug"]: ImageCredit(**item) for item in raw}


def picture(slug: str) -> ImageCredit:
    """Image file, size, alt text and attribution of a curated photo."""
    return _credits()[slug]


def image_credits() -> list[ImageCredit]:
    """Every curated photo with its author and licence (credits page)."""
    return sorted(_credits().values(), key=lambda credit: credit.alt)


